PLAN_MARGIN: Final = 1.1  # 10 % above the estimate: the bot's denominators vary, pairs fail
GENERATED: Final = ("generated", "judged", "skipped")


class EnoughAlready(EvalError):
    """The sample already has enough expected events for every share: nothing to plan."""


@dataclass
class StylePlan:
    """The outcome of :func:`plan_style_sample`."""

    run: RunView
    contexts: int  # distinct hold-out contexts this plan answers
    replies: int  # replies per backend this plan asks for
    copies: int  # the most replies one context gets in this plan (1: no context twice)
    needed: int  # replies per backend this plan was sized for
    have: int  # replies per backend the sample already had (the smallest)
    available: int  # usable contexts of the hold-out
    estimated_usd: float
    batch_ids: list[str] = field(default_factory=list)
    per_reply: dict[str, float] = field(default_factory=dict)  # expected events per reply

    @property
    def rarest(self) -> str | None:
        """The share that decided the size (the fewest expected events per reply)."""
        return min(self.per_reply, key=lambda key: self.per_reply[key], default=None)


def sample_runs(store: EvalStore, model_id: str) -> list[RunView]:
    """The style samples drawn for ``model_id``, newest first (a cancelled one counts nothing)."""
    return [
        run
        for run in store.list_runs("style", limit=RESOLVE_LIMIT)
        if run.params.get("purpose") == SAMPLE_PURPOSE
        and run.params.get(MODEL_PARAM) == model_id
        and run.status != "cancelled"
    ]


def replica_seed(sample_key: str, backend: str, replica: int) -> int:
    """The seed of one copy of a context: reproducible, and different for every copy."""
    return stable_seed(sample_key, backend, "style-sample", str(replica))


def replicate(
    pool: Sequence[DrawnSample], count: int, used: Mapping[str, int]
) -> list[tuple[DrawnSample, int]]:
    """``count`` more answers to the contexts of ``pool``, round by round, with their copy number.

    ``used`` is how many answers each context already has; every context of the pool gets one
    more before any gets two more (the copies are spread as evenly as the pool allows).
    """
    counts = Counter(used)
    found: list[tuple[DrawnSample, int]] = []
    for index in range(count if pool else 0):
        sample = pool[index % len(pool)]
        found.append((sample, counts[sample.sample_key]))
        counts[sample.sample_key] += 1
    return found


def size_sample(
    services: Services,
    store: EvalStore,
    earlier: Sequence[RunView],
    backends: Sequence[str],
    reference: ProfileMetrics,
    channel: Abilities,
) -> tuple[int, int, dict[str, float]]:
    """``(replies per backend to plan, replies per backend there already, events per reply)``.

    A backend without replies yet is sized from her denominators (:func:`her_units_per_reply`);
    a backend with replies from what they were: only a share still short of events asks for
    more, as many as the bot's own denominators say it needs - with the margin either way.
    """
    estimate = her_units_per_reply(reference)
    per_reply = expected_per_reply(reference, channel, estimate)
    need, have = 0, []
    for backend in backends:
        replies = sum(
            len(store.items(run.id, backend=backend, status=list(GENERATED), with_payload=False))
            for run in earlier
        )
        have.append(replies)
        if replies == 0:
            need = max(need, math.ceil(replies_needed(reference, channel, estimate) * PLAN_MARGIN))
            continue
        report = style_of_runs(services, store, earlier, backend)
        if not report.insufficient:
            continue
        measured = units_per_reply(report, replies)
        per_reply = expected_per_reply(reference, channel, measured)
        total = math.ceil(replies_needed(reference, channel, measured) * PLAN_MARGIN)
        need = max(need, total - replies)
    return need, min(have, default=0), per_reply


async def plan_style_sample(
    services: Services,
    backends: Sequence[str],
    *,
    model_id: str,
    seed: int | None = None,
    kit: SandboxKit | None = None,
    models: StyleModels | None = None,
    extra_params: Mapping[str, Any] | None = None,
    since: datetime | None = None,
) -> StylePlan:
    """Size, draw and queue the style sample of ``model_id`` (see the module description).

    ``since`` is the cut-off the model was trained with: no context before it is drawn (D-886).
    """
    check_backends(services, backends, models)
    problems = readiness_problems(services, backends)
    if problems:
        raise EvalError("; ".join(problems))
    profile = load_profile(services, "pre_holdout")
    if profile is None:  # readiness_problems says so first; kept for the type checker
        raise EvalError("there is no pre-holdout profile; run `twin profile rebuild` first")
    store = EvalStore(services.db, services.clock)
    earlier = sample_runs(store, model_id)
    for run in earlier:
        pending = store.counts(run.id)["pending"]
        if pending:
            raise EvalError(
                f"the style sample {run.id} still has {pending} replies to generate: "
                f"finish it first (twin model evaluate {model_id} --resume {run.id})"
            )
    own = kit is None
    sandbox_kit = kit or build_sandbox(services, mode=SandboxMode.HOLDOUT)
    try:
        channel = abilities_of(sandbox_kit.sandbox.channel.capabilities())
        need, have, per_reply = size_sample(
            services, store, earlier, backends, profile.metrics, channel
        )
        if need <= 0:
            raise EnoughAlready(
                f"the style sample of {model_id} has {have} replies per way and every share has "
                f"{MIN_EXPECTED_EVENTS} expected events: nothing more to generate"
            )
        chosen_seed = new_seed() if seed is None else seed
        used = Counter(
            item.sample_key
            for run in earlier
            for item in store.items(run.id, backend=backends[0], with_payload=False)
        )
        drawer = SampleDrawer(services, since=since)
        fresh: DrawResult = await asyncio.to_thread(
            lambda: drawer.draw(need, seed=chosen_seed, exclude=set(used))
        )
        picks = [(sample, used[sample.sample_key]) for sample in fresh.samples]
        if len(picks) < need:  # the hold-out has no more new contexts: answer them again
            every: DrawResult = await asyncio.to_thread(
                lambda: drawer.draw(max(1, fresh.holdout_blocks), seed=chosen_seed)
            )
            taken = used + Counter(sample.sample_key for sample in fresh.samples)
            picks += replicate(every.samples, need - len(picks), taken)
        if not picks:
            raise EvalError(
                f"the hold-out has no usable context ({fresh.holdout_blocks} reply blocks; "
                f"left out: {dict(fresh.excluded)})"
            )
        thinking = str(services.runtime.get(THINKING_CHAT))
        unique = list({sample.sample_key: sample for sample, _ in picks}.values())
        prices = await price_pairs(
            services, sandbox_kit, DrawResult(samples=unique), backends, thinking
        )
        run = store.create_run(
            "style",
            mode="holdout",
            backends=backends,
            params={
                **(extra_params or {}),
                MODEL_PARAM: model_id,
                "purpose": SAMPLE_PURPOSE,
                "seed": chosen_seed,
                "thinking_mode": thinking,
                "holdout_cutoff": holdout_cutoff(services).isoformat(),
                "drawn_since": drawer.start().isoformat(),
                "min_expected": MIN_EXPECTED_EVENTS,
                "margin": PLAN_MARGIN,
                "needed": need,
                "have": have,
                "contexts": len(unique),
                "replies": len(picks),
                "available": fresh.available,
                "holdout_blocks": fresh.holdout_blocks,
                "excluded": dict(fresh.excluded),
                "expected_per_reply": {key: round(value, 6) for key, value in per_reply.items()},
            },
        )
        store.add_items(run.id, list(sample_items(picks, backends)))
        run, batch_ids, total = queue_generation(sandbox_kit, store, run, prices)
        return StylePlan(
            run=run,
            contexts=len(unique),
            replies=len(picks),
            copies=Counter(sample.sample_key for sample, _ in picks).most_common(1)[0][1],
            needed=need,
            have=have,
            available=fresh.available,
            estimated_usd=total,
            batch_ids=batch_ids,
            per_reply=per_reply,
        )
    finally:
        if own:
            await sandbox_kit.aclose()


def sample_items(
    picks: Sequence[tuple[DrawnSample, int]], backends: Sequence[str]
) -> Iterator[NewItem]:
    """One item per (context copy, backend); the copy number and its seed go with it."""
    for sample, replica in picks:
        for backend in backends:
            yield NewItem(
                sample_key=sample.sample_key,
                backend=backend,
                at=sample.at,
                payload={
                    **sample.payload(),
                    "seed": replica_seed(sample.sample_key, backend, replica),
                    "replica": replica,
                },
                period=sample.period,
                length_bin=sample.length_bin,
            )


