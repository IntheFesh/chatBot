"""The style sample of a model: the replies M5's style criterion is judged on (R-SRV-005).

Round 18 (user decision, D-852).  The style metrics of a model are no longer measured on the pairs
of its blind test: those are as many as the user can judge (``--n``, 65 by default), and the rare
shares of her style - a comma in about 3 % of her texts - need far more replies before the +-30 % of
R-EVAL-002 says anything (a perfect copy of her passes the three rare shares together about a
quarter of the time on 65 contexts).  The sample is sized from her profile instead, apart from
the blind test:

* the rarest share the sandbox channel can show needs :data:`MIN_EXPECTED_EVENTS` expected events:
  ``replies = ceil(50 / (her rate x her denominator per reply))`` (some 700 for her comma rate),
  plus :data:`PLAN_MARGIN` for the spread of the bot's own denominators and the pairs that fail to
  generate - what decides in the end is the bot's real denominator when the sample is measured;
* the contexts are drawn from the hold-out the way a blind test draws them (the same checks,
  stratified) - and only after the cut-off the model was trained with (``since``, locked in
  ``model_registry``, round 18, D-886) - as many as needed, at most every usable one; when the
  hold-out has fewer, every
  context is answered more than once, each copy with a seed of its own (``replica`` and ``seed``
  are kept in the item, so the sample can be made again);
* a second plan for the same model tops the sample up: it measures what was generated, sizes the
  rest from the bot's own denominators, and draws contexts the sample has not used before it
  answers any of them again;
* the generation is a one-time batch like a blind test, priced from the prompts and waiting for
  ``twin jobs approve`` (the ``style`` backend costs nothing; ``hybrid`` costs DeepSeek's plan of
  each reply).  The blind test keeps its own ``--n``.

A sample is a run of kind ``style`` whose ``params.purpose`` is ``sample`` (no new kind, so no
migration), drawn for one model (``params.model_id``); its items are generated by the ordinary
``eval_generate`` jobs and nobody judges them.
"""

