EVAL_LOG: Final = "llama-server-eval.log"
TUNNEL_WAIT_S: Final = 90.0
STOP_WAIT_S: Final = 20.0


@dataclass
class _Prepared:
    """An endpoint that serves a model, and what to stop when the pool ends."""

    endpoint: str
    manager: LlamaServerManager | None = None
    tunnel: TunnelManager | None = None
    task: asyncio.Task[None] | None = None
    checked: bool = False  # the tokens were compared and are the same


# -------------------------------------------------------------------- planning


def preflight(services: Services, model: ModelView, program: LocalProgram | None = None) -> None:
    """Refuse early what would fail after the batches were approved: nothing is started here."""
    try:
        require_servable(services, model)
    except ActivationRefused as exc:
        raise EvaluationError(exc.message) from exc
    if model.kind == "gguf":
        try:
            if program is None:
                resolve_program(services)
        except ServeError as exc:
            raise EvaluationError(str(exc)) from exc
        path = model_path(services, model)
        if not path.is_file():
            raise EvaluationError(f"the model file {path} does not exist")
    else:
        try:
            target_from_settings(
                services.settings.autodl, services.secrets, tunnel_known_hosts(services)
            )
        except RemoteError as exc:
            raise EvaluationError(str(exc)) from exc


def tunnel_known_hosts(services: Services) -> Path:
    """Where ``twin train remote connect`` saved the trusted host keys."""
    return services.paths.data_dir / "training" / "known_hosts"


async def plan_model_evaluation(
    services: Services,
    reference: str,
    n: int,
    *,
    seed: int | None = None,
    program: LocalProgram | None = None,
) -> tuple[ModelView, BlindPlan]:
    """Draw ``n`` new hold-out contexts and queue their generation for all three backends."""
    try:
        model = find_model(services.db, reference)
    except RegistryError as exc:
        raise EvaluationError(str(exc)) from exc
    preflight(services, model, program)
    pinned = StyleModels(services.db, mode=services.settings.style_model.mode, pinned=model.id)
    plan = await plan_blind(
        services,
        EVAL_BACKENDS,
        n,
        seed=seed,
        models=pinned,
        extra_params={MODEL_PARAM: model.id, "model_sha256": model.sha256},
    )
    return model, plan


# --------------------------------------------------------------------- servers


class EvaluationServers:
    """The servers of the models under evaluation (see the module description)."""

    def __init__(
        self,
        services: Services,
        *,
        tokenizers: TokenizerSource | None = None,
        job: ProcessJob | None = None,
        connect: Connector | None = None,
        timings: ServerTimings | None = None,
        check_file: Callable[[ModelView, Path], None] = verify_model_file,
        program: LocalProgram | None = None,
    ) -> None:
        self._services = services
        self._program = program
        self._tokenizers = tokenizers or TokenizerSource(services)
        self._job = job
        self._connect = connect
        self._timings = timings
        self._check_file = check_file
        self._prepared: dict[str, _Prepared] = {}
        self._lock = asyncio.Lock()

    async def style_runtime(
        self, llm: LlmRuntime, model_id: str
    ) -> tuple[StyleRuntime, StyleModels]:
        """The style backends of the sandbox, bound to the server of ``model_id``.

        The server is started if it is not running and its tokens are compared with the training
        tokenizer before the first prompt (:class:`EvaluationError` when they differ).
        """
        services = self._services
        model = get_model(services.db, model_id)
        prepared = await self._prepare(model)
        await self._ensure_checked(model, prepared)
        config = services.settings.style_model
        pinned = StyleModels(services.db, mode=config.mode, pinned=model.id)
        client = client_for(config, services.clock, endpoint=prepared.endpoint)
        return StyleRuntime.from_services(services, llm, client=client, models=pinned), pinned

    async def verify(self, model: ModelView) -> TokenizationReport:
        """Start the server of ``model`` and compare its tokens (``twin model verify``).

        The verdict is recorded on the model (the application is woken to look at it).
        """
        prepared = await self._prepare(model)
        report = await self._compare(model, prepared.endpoint, bump_state=None)
        prepared.checked = report.ok
        return report

    async def _prepare(self, model: ModelView) -> _Prepared:
        async with self._lock:
            found = self._prepared.get(model.id)
            if found is None:
                started = (
                    self._start_local(model) if model.kind == "gguf" else self._start_remote(model)
                )
                found = await started
                self._prepared[model.id] = found
            return found

    async def _compare(
        self, model: ModelView, endpoint: str, *, bump_state: bool | None = False
    ) -> TokenizationReport:
        config = self._services.settings.style_model
        client = client_for(config, self._services.clock, endpoint=endpoint)
        try:
            return await compare_tokens(
                self._services, model, client, self._tokenizers, bump_state=bump_state
            )
        finally:
            await client.aclose()

    async def _ensure_checked(self, model: ModelView, prepared: _Prepared) -> None:
        if prepared.checked:
            return
        report = await self._compare(model, prepared.endpoint)
        if not report.ok:
            raise EvaluationError(
                "\n".join(
                    [
                        "the tokens of the server differ from the training tokenizer:",
                        *report.lines(),
                    ]
                )
            )
        prepared.checked = True

    # -- a GGUF on this computer ----------------------------------------------------

    async def _start_local(self, model: ModelView) -> _Prepared:
        services = self._services
        config = services.settings.style_model
        try:
            program = self._program or resolve_program(services)
        except ServeError as exc:
            raise EvaluationError(str(exc)) from exc
        path = model_path(services, model)
        try:
            await asyncio.to_thread(self._check_file, model, path)
        except ServeError as exc:
            raise EvaluationError(str(exc)) from exc
        if same_model_file(await served_model_path(config.endpoint), path):
            log.info("evaluation_uses_running_server", model=model.id)
            return _Prepared(config.endpoint)
        port = config.serve.eval_port
        if port == primary_port(config):
            raise EvaluationError(
                "style_model.serve.eval_port must differ from the port of style_model.endpoint"
            )
        local = build_local_server(
            services,
            model,
            program,
            port=port,
            tokenizers=self._tokenizers,
            job=self._job,
            timings=self._timings,
            log_name=EVAL_LOG,
            warm=False,
            gate=False,
        )
        manager, client, endpoint = local.manager, local.client, local.endpoint
        timings = self._timings or default_timings(services)
        task = asyncio.create_task(manager.run(), name=f"evaluation-server:{model.id}")
        prepared = _Prepared(endpoint, manager=manager, task=task)
        try:
            await self._wait_for(manager, task, timings.start_timeout_s + 30.0)
        except BaseException:
            await self._stop(prepared)
            await client.aclose()
            raise
        await client.aclose()
        return prepared

    async def _wait_for(
        self, manager: LlamaServerManager, task: asyncio.Task[None], limit_s: float
    ) -> None:
        waiter = asyncio.ensure_future(
            manager.wait_state(
                {ServerState.READY, ServerState.BLOCKED, ServerState.BACKOFF}, limit_s
            )
        )
        try:
            await asyncio.wait({waiter, task}, return_when=asyncio.FIRST_COMPLETED)
        finally:
            if not waiter.done():
                waiter.cancel()
            await asyncio.gather(waiter, return_exceptions=True)
        if task.done():
            error = task.exception()
            raise EvaluationError(f"the llama-server could not be started: {error}") from error
        if manager.state is ServerState.BLOCKED:
            blocked = manager.blocked
            reason = blocked.detail if blocked is not None else manager.snapshot().detail
            raise EvaluationError(
                f"the model was refused ({blocked.reason if blocked else 'blocked'}): {reason}; "
                "`twin model verify` shows the differences"
            )
        if manager.state is not ServerState.READY:
            # a start that failed once is reported at once (with the end of the server's log in the
            # detail); an evaluation is attended, the application's restart loop is not wanted here
            detail = manager.snapshot().detail or manager.state
            raise EvaluationError(f"the llama-server did not become ready: {detail}")

    # -- an adapter on the rented instance -------------------------------------------

    async def _start_remote(self, model: ModelView) -> _Prepared:
        services = self._services
        config = services.settings.style_model
        endpoint = f"http://127.0.0.1:{config.tunnel.local_port}"
        probe = client_for(config, services.clock)
        try:
            if (await probe.health()).ok:  # the application's tunnel, or `twin model tunnel start`
                return _Prepared(endpoint)
        finally:
            await probe.aclose()
        try:
            target = target_from_settings(
                services.settings.autodl, services.secrets, tunnel_known_hosts(services)
            )
        except RemoteError as exc:
            raise EvaluationError(str(exc)) from exc
        tunnel = TunnelManager(
            target,
            local_port=config.tunnel.local_port,
            remote_port=config.tunnel.remote_port,
            clock=services.clock,
            timings=TunnelTimings(config.tunnel.backoff_start_s, config.tunnel.backoff_max_s),
            connect=self._connect,
        )
        task = asyncio.create_task(tunnel.run(), name=f"evaluation-tunnel:{model.id}")
        prepared = _Prepared(endpoint, tunnel=tunnel, task=task)
        try:
            await self._wait_for_tunnel(tunnel, task)
            probe = client_for(config, services.clock)
            try:
                health = await probe.health()
            finally:
                await probe.aclose()
            if not health.ok:
                raise EvaluationError(
                    "the tunnel is up, but vLLM does not answer on the instance "
                    f"({health.detail}); start it with training/autodl/serve_vllm.sh"
                )
        except BaseException:
            await self._stop(prepared)
            raise
        return prepared

    async def _wait_for_tunnel(self, tunnel: TunnelManager, task: asyncio.Task[None]) -> None:
        clock = self._services.clock
        deadline = clock.monotonic() + TUNNEL_WAIT_S
        while tunnel.state is not TunnelState.UP:
            if task.done():
                raise EvaluationError(f"the tunnel stopped: {task.exception()}")
            if tunnel.state is TunnelState.BLOCKED:
                raise EvaluationError(tunnel.snapshot().detail)
            if clock.monotonic() >= deadline:
                raise EvaluationError(
                    f"the tunnel to the instance did not come up: {tunnel.snapshot().detail}"
                )
            await clock.sleep(0.2)

    # -- ending ------------------------------------------------------------------

    async def _stop(self, prepared: _Prepared) -> None:
        if prepared.manager is not None:
            await prepared.manager.stop()
        if prepared.tunnel is not None:
            await prepared.tunnel.stop()
        if prepared.task is not None:
            with contextlib.suppress(asyncio.CancelledError, Exception):
                await asyncio.wait_for(prepared.task, STOP_WAIT_S)

    async def aclose(self) -> None:
        """End every server and tunnel this pool started."""
        async with self._lock:
            prepared, self._prepared = list(self._prepared.values()), {}
        for item in prepared:
            await self._stop(item)


# ----------------------------------------------------- the owner of the servers


def install_servers(servers: EvaluationServers | None) -> None:
    """Make ``servers`` the pool the evaluation jobs of this process use (``None``: none)."""
    install_model_styles(servers)


def installed_servers() -> EvaluationServers | None:
    installed = installed_model_styles()
    return installed if isinstance(installed, EvaluationServers) else None


