"""``twin model evaluate``: the same new contexts through DeepSeek and through the model.

A model that is not active cannot be evaluated through the running bot, so the evaluation has
servers of its own:

* the **plan** (:func:`plan_model_evaluation`) is the blind test of round 09b with three backends
  on one set of contexts - ``deepseek``, ``style`` (the model alone) and ``hybrid`` (DeepSeek plans,
  the model writes) - drawn from the hold-out, never from a context an earlier blind test used.  The
  run carries ``model_id``; the pairs are generated by the ordinary ``eval_generate`` jobs, priced
  and approved like any one-time batch (R-LLM-014);
* the **servers** (:class:`EvaluationServers`) are started when a job needs them and ended with
  their owner: the local ``llama-server`` of the candidate on ``style_model.serve.eval_port`` (the
  server of the running application on its own port is not touched - unless it already serves this
  very file, then it is used), or the SSH tunnel to the instance in vLLM mode.  Each is compared
  with the training tokenizer before a single prompt is sent (a model whose tokens differ is
  refused);
* the **style runtime** for the sandbox renders with the versions the model is locked to
  (``StyleModels(pinned=...)``) and talks to that endpoint; DeepSeek, post-processing and the
  rest are the bot's own, exactly as for ``twin eval blind``.

The owner of the servers installs them with :func:`install_servers` for as long as it lives: the
running application (the serving component) for the whole run, ``twin model evaluate --foreground``
for the length of its jobs.  A job that finds none cannot generate the model's pairs and says so.
"""

